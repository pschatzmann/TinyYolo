#!/usr/bin/env python3
"""Converts files into a C header with PROGMEM byte arrays (for models embedded in flash).

usage: bin2header.py output.h name1=file1 [name2=file2 ...]

Each name becomes `static const uint8_t name[] PROGMEM = {...};`. Use BufferStream
(core/BufferStream.h) to read the arrays through the Stream interface.
"""

import sys


def main(argv):
    if len(argv) < 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    out_path = argv[1]
    with open(out_path, "w") as out:
        out.write("// Generated by tools/bin2header.py. Do not edit.\n")
        out.write("#pragma once\n")
        out.write("#ifndef PROGMEM\n#define PROGMEM  // flash placement; empty on boards that read const data directly\n#endif\n\n")
        for pair in argv[2:]:
            name, path = pair.split("=", 1)
            with open(path, "rb") as f:
                data = f.read()
            out.write(f"static const uint8_t {name}[] PROGMEM = {{\n")
            for i in range(0, len(data), 16):
                row = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
                out.write(f"  {row},\n")
            out.write("};\n\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

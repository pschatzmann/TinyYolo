#!/usr/bin/env python3
"""Generates the C++ operation table for YOLO11 (see src/TinyYolo/graph/Graph.h).

usage: yolo_gen_graph.py yolo11n_graph.json output.inc [namespace]

The JSON comes from the export of the Ultralytics model (scratchpad/yolo11/graph.py export).
Concatenations with more than two inputs become pairs, with temporary tensor ids. Max-pool
padding is written as the total padding (2 x symmetric padding), as Backend::maxPool expects.
"""
import json
import sys


def main(json_path, out_path, namespace="yolo11"):
    data = json.load(open(json_path))
    ops_out = []
    max_id = 0
    for op in data["ops"]:
        for key in ("inp", "out"):
            v = op.get(key)
            if isinstance(v, list):
                max_id = max([max_id] + v)
            elif isinstance(v, int):
                max_id = max(max_id, v)
    next_id = max_id + 1

    def emit(kind, inputs, out, w=-1, b=-1, k=0, s=0, p=0, g=0, silu=False, index=0,
             w2=-1, b2=-1, w3=-1, b3=-1, heads=0, key_dim=0, head_dim=0, q=-1, q2=-1, q3=-1):
        ins = list(inputs) + [0] * (4 - len(inputs))
        # Field order must match struct GraphOp in src/TinyYolo/graph/Graph.h.
        fields = [
            "GraphOpKind::" + kind,
            str(len(inputs)),
            "{" + ", ".join(str(i) for i in ins) + "}",
            str(out), str(w), str(b), str(k), str(s), str(p), str(g),
            "true" if silu else "false",
            str(index), str(w2), str(b2), str(w3), str(b3),
            str(heads), str(key_dim), str(head_dim), str(q), str(q2), str(q3),
        ]
        ops_out.append("  {" + ", ".join(fields) + "},")

    for op in data["ops"]:
        kind = op["kind"]
        if kind == "conv":
            emit("Conv", [op["inp"]], op["out"], w=op["w"], b=op["b"], k=op["k"], s=op["s"],
                 p=op["p"], g=op["g"], silu=op["act"] == "silu", q=op.get("q", -1))
        elif kind == "add":
            emit("Add", op["inp"], op["out"])
        elif kind == "chunk":
            emit("Chunk", [op["inp"]], op["out"], index=op["index"])
        elif kind == "concat":
            ins = op["inp"]
            acc = ins[0]
            for j in range(1, len(ins)):
                target = op["out"] if j == len(ins) - 1 else next_id
                if target != op["out"]:
                    next_id += 1
                emit("Concat", [acc, ins[j]], target)
                acc = target
        elif kind == "maxpool":
            emit("MaxPool", [op["inp"]], op["out"], k=op["k"], s=op["s"], p=2 * op["p"])
        elif kind == "upsample2":
            emit("Upsample", [op["inp"]], op["out"])
        elif kind == "attention":
            emit("Attention", [op["inp"]], op["out"], w=op["qkv_w"], b=op["qkv_b"], w2=op["pe_w"],
                 b2=op["pe_b"], w3=op["proj_w"], b3=op["proj_b"], heads=op["heads"],
                 key_dim=op["key_dim"], head_dim=op["head_dim"], q2=op.get("q2", -1), q3=op.get("q3", -1))
        else:
            raise ValueError(kind)

    tensor_count = next_id + 1
    params = []
    for p in data["params"]:
        dims = p["shape"] + [0] * (4 - len(p["shape"]))
        params.append("  {%d, %d, {%s}}," % (p["offset"], len(p["shape"]), ", ".join(str(d) for d in dims)))

    outputs = []
    for layer, tid in sorted(((int(k), v) for k, v in data["outputs"].items())):
        outputs.append("  {%d, %d}," % (layer, tid))

    with open(out_path, "w") as f:
        f.write("// Generated by tools/yolo/yolo_gen_graph.py from the %s export. Do not edit.\n" % namespace)
        f.write("#pragma once\n")
        f.write('#include "TinyYolo/app/GraphYolo11.h"\n\n')
        f.write("namespace %s {\n\n" % namespace)
        f.write("using tinyyolo::GraphOpKind;\n\n")
        f.write("static const tinyyolo::GraphParam kParams[] = {\n")
        f.write("\n".join(params) + "\n};\n")
        f.write("static const tinyyolo::GraphOp kOps[] = {\n")
        f.write("\n".join(ops_out) + "\n};\n")
        quant = data.get("quant", [])
        f.write("/// Int8 convolutions: offsets into the int8 weights and the scales, and activation scales.\n")
        f.write("static const tinyyolo::GraphQuant kQuant[] = {\n")
        for e in quant:
            f.write("  {%d, %d, %.9ef, %.9ef},\n" % (e["w_offset"], e["s_offset"], e["in_scale"], e["out_scale"]))
        f.write("};\n")
        f.write("static const int kQuantCount = %d;\n" % len(quant))
        # Per-tensor activation scales (the same weights and operations, one scale per tensor).
        f.write("/// The same table with one scale per tensor (no scale shared by concatenations and the like).\n")
        f.write("static const tinyyolo::GraphQuant kQuantPerTensor[] = {\n")
        for e in data.get("quant_per_tensor", []):
            f.write("  {%d, %d, %.9ef, %.9ef},\n" % (e["w_offset"], e["s_offset"], e["in_scale"], e["out_scale"]))
        f.write("};\n")
        f.write("static const int kQuantPerTensorCount = %d;\n" % len(data.get("quant_per_tensor", [])))
        f.write("static const int kOpCount = %d;\n" % len(ops_out))
        f.write("static const int kParamCount = %d;\n" % len(params))
        f.write("static const int kTensorCount = %d;\n" % tensor_count)
        f.write("static const int kInputId = %d;\n" % data["input_id"])
        f.write("/// Tensor id of the output of each Ultralytics layer: {layer, tensor id}.\n")
        f.write("static const int kOutputs[][2] = {\n")
        f.write("\n".join(outputs) + "\n};\n")
        f.write("static const int kOutputCount = %d;\n\n" % len(outputs))
        det = data["detect"]
        f.write("/// Detect head: per scale {box tensor id, class tensor id}, and the strides.\n")
        f.write("static const int kDetectHeads[][2] = {\n")
        f.write("\n".join("  {%d, %d}," % (b, c) for b, c in det["heads"]) + "\n};\n")
        f.write("static const int kDetectStrides[] = {%s};\n" % ", ".join(str(s) for s in det["strides"]))
        f.write("static const int kDetectClasses = %d;\n" % det["classes"])
        f.write("static const int kDetectRegMax = %d;\n\n" % det["reg_max"])
        f.write("/// The model description for tinyyolo::GraphYolo11 (kQuant: the shared-scale table).\n")
        f.write("static const tinyyolo::GraphModel kModel = {kOps, kOpCount, kParams, kParamCount, kTensorCount,\n")
        f.write("    kInputId, kQuant, kDetectHeads, kDetectStrides, %d, kDetectClasses, kDetectRegMax, 640};\n\n" % len(det["strides"]))
        f.write("}  // namespace %s\n" % namespace)
    print("ops:", len(ops_out), "params:", len(params), "tensors:", tensor_count, "outputs:", len(outputs))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
